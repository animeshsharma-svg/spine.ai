/**
 * Learn the field-level API assertions from the responses real journeys
 * captured, and publish them twice:
 *
 *   data/api-assertions.json          the machine catalog the journey runner
 *                                     evaluates on every run (apiAssertions.ts)
 *   test-cases/api-field-assertions.md  every assertion as a human test case in
 *                                     the catalog format, so the 648 written
 *                                     cases gain one case per field check
 *   test-cases/api-request-negatives.md  Postman-style negative cases derived
 *                                     from each request's own body: omit a field,
 *                                     send the wrong type → the app must refuse
 *
 *   tsx scripts/build-api-assertions.ts [--cap 45]
 *
 * Then `npm run cases:import` folds both markdown files into the catalog.
 * Re-run after new journey runs: assertion ids are stable across rebuilds.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  ASSERTIONS_FILE,
  STEP_CODE,
  buildAssertionCatalog,
  endpointOf,
  loadAssertionCatalog,
  type AssertionCatalog,
  type FieldAssertion,
  type ResponseSample,
} from "../src/checks/apiAssertions.js";
import { JOURNEY_ORDER, STEP_META, type JourneyRecord, type StepKind } from "../src/checks/journeyModel.js";
import { humanCase } from "../src/checks/humanize.js";

const here = dirname(fileURLToPath(import.meta.url));
const RUNS = join(here, "..", "data", "runs");
const CASES = join(here, "..", "..", "test-cases");
const argv = process.argv.slice(2);
const cap = Number(argv[argv.indexOf("--cap") + 1]) || 60;

// ── 1. gather samples from every run that kept response bodies ─────────────
const samples: ResponseSample[] = [];
const eventTypesByStep = new Map<StepKind, Set<string>>();
for (const f of readdirSync(RUNS).filter((x) => x.endsWith(".json")).sort()) {
  let run: any;
  try {
    run = JSON.parse(readFileSync(join(RUNS, f), "utf8"));
  } catch {
    continue;
  }
  const journey: JourneyRecord | undefined = run?.journey;
  if (!journey?.steps?.length) continue;
  const made: Record<string, string> = {};
  for (const st of journey.steps) {
    if (st.call && st.response !== undefined && st.verdict !== "not-run") {
      samples.push({
        step: st.kind,
        title: st.title,
        method: st.call.method,
        path: st.call.path,
        status: st.status ?? 0,
        ms: st.ms ?? 0,
        body: st.call.body,
        response: st.response,
        madeBefore: { ...made },
        run: f,
      });
      const set = eventTypesByStep.get(st.kind) ?? new Set<string>();
      set.add(journey.label);
      eventTypesByStep.set(st.kind, set);
    }
    if (st.produced) Object.assign(made, st.produced);
  }
}
if (!samples.length) {
  console.error("No captured responses yet. Run a journey first: npx tsx scripts/capture-journey-samples.ts");
  process.exit(1);
}

// ── 2. infer + keep ids stable ─────────────────────────────────────────────
const previous = loadAssertionCatalog();
const catalog: AssertionCatalog = buildAssertionCatalog(samples, previous, cap);
// Every check also written as a tester would write it — title, steps, expected
// result in plain English — so the catalog, the dashboard and the report can
// all show it that way; the machine check stays attached for engineers.
for (const [k, e] of Object.entries(catalog.steps)) {
  const meta = STEP_META[k as StepKind];
  for (const a of e.assertions) a.human = humanCase(a, meta.title, meta.actor);
}
writeFileSync(ASSERTIONS_FILE, JSON.stringify(catalog, null, 2) + "\n");

// ── 3. the field assertions as human cases ─────────────────────────────────
const P: Record<string, string> = { critical: "P0", major: "P1", minor: "P2" };
const OP_ORACLE = (a: FieldAssertion): string => {
  const v = a.value !== undefined ? ` ${JSON.stringify(a.value)}` : "";
  const r = a.ref ? ` ← ${a.ref}` : "";
  return `\`${a.op}${a.path ? ` ${a.path}` : ""}${v}${r}\``;
};
const ordered = JOURNEY_ORDER.filter((k) => catalog.steps[k]);
const md: string[] = [];
md.push("# API field assertions — Postman-style checks on every journey request", "");
md.push(
  "Generated by `prototype/scripts/build-api-assertions.ts` from the responses real API journeys captured. " +
    "Each case is one assertion the journey runner evaluates **live on every run** (`prototype/src/checks/apiAssertions.ts`) — " +
    "the report shows it under the step as passed / failed / not checked. Required = present in every captured response; " +
    "a format is claimed only when the field name names it and every observed value conforms. Do not edit by hand — re-run the script.",
  "",
);
md.push(`_Built ${catalog.generatedAt} from ${samples.length} captured responses across ${catalog.fromRuns.length} run(s)._`, "");
let total = 0;
ordered.forEach((k, idx) => {
  const e = catalog.steps[k];
  const meta = STEP_META[k];
  const types = [...(eventTypesByStep.get(k) ?? [])].join(", ");
  md.push(`## ${idx + 1}. ${meta.title} — \`${e.endpoint}\``, "");
  md.push(`Step \`${k}\` (${meta.actor})${meta.postman ? ` · Postman: ${meta.postman}` : ""} · seen in: ${types} · ${e.samples} sample(s).`, "");
  for (const a of e.assertions) {
    total++;
    const h = a.human!;
    md.push(`#### ${a.id} — ${h.title.replace(/`/g, "")}`);
    md.push(`- **Why it matters.** ${a.why}`);
    md.push(`- **Setup.** A ${meta.actor} walking the API journey (${types || "any event type"}), at the step "${meta.title}".`);
    md.push(`- **Steps.** ${h.steps}`);
    md.push(`- **Expected.** ${h.expected}`);
    md.push(`- **Oracle.** Checked automatically on every API journey run; the report shows what actually came back. Engine check: ${OP_ORACLE(a)}, learned from ${a.samples} real response(s).`);
    md.push(`- **Trace.** ${P[a.severity]} · automate · \`apiAssertions.ts\` · \`${k}\``, "");
  }
});
writeFileSync(join(CASES, "api-field-assertions.md"), md.join("\n"));

// ── 4. request-side negatives, from each step's own body ───────────────────
/** Leaves of the request body worth mutating (scalars, capped per step). */
function reqLeaves(v: unknown, p = "", out: Array<[string, unknown]> = [], depth = 0): Array<[string, unknown]> {
  if (depth > 4) return out;
  if (Array.isArray(v)) {
    if (v.length) reqLeaves(v[0], `${p}[0]`, out, depth + 1);
  } else if (v && typeof v === "object") {
    for (const [k, x] of Object.entries(v as Record<string, unknown>)) reqLeaves(x, p ? `${p}.${k}` : k, out, depth + 1);
  } else if (p && v !== null && v !== undefined && v !== "" && v !== "<redacted>") out.push([p, v]);
  return out;
}
const IMPORTANT = /(uuid|_id|Id$|status|quantity|value|price|amount|unit|title|name|email|time|date|start|end)/i;
const neg: string[] = [];
neg.push("# API request negatives — omit a field, send the wrong type", "");
neg.push(
  "Generated by `prototype/scripts/build-api-assertions.ts` from the request bodies the API journey actually sends. " +
    "Each case mutates ONE field of a real, working request and expects the app to refuse it cleanly (4xx, nothing created or changed) " +
    "rather than accept bad data or break (5xx). Run against a sandbox event only.",
  "",
);
let negN = 0;
let sec = 0;
for (const k of ordered) {
  const e = catalog.steps[k];
  if (!/^(POST|PATCH|PUT)/.test(e.endpoint)) continue;
  const smp = samples.find((s) => s.step === k && endpointOf(s.method, s.path) === e.endpoint && s.body && s.status >= 200 && s.status < 300);
  if (!smp) continue;
  const fields = reqLeaves(smp.body)
    .filter(([p]) => IMPORTANT.test(p.split(".").pop() ?? ""))
    .slice(0, 8);
  if (!fields.length) continue;
  sec++;
  neg.push(`## ${sec}. ${STEP_META[k].title} — \`${e.endpoint}\``, "");
  let i = 0;
  const code = STEP_CODE[k];
  for (const [path, val] of fields) {
    const wrong = typeof val === "number" ? `"not-a-number"` : typeof val === "boolean" ? `"yes"` : `12345`;
    for (const [what, how, pr] of [
      ["is omitted", `Remove \`${path}\` from the body`, "P1"],
      ["has the wrong type", `Send \`${path}\` as ${wrong} (it is ${typeof val} in a working request)`, "P1"],
    ] as const) {
      i++;
      negN++;
      neg.push(`#### API-N${code}-${String(i).padStart(3, "0")} — ${STEP_META[k].title}: \`${path}\` ${what}`.replace(/`/g, ""));
      neg.push(`- **Why it matters.** \`${path}\` is part of the working request for this step; the server must validate it rather than store bad data or fail with a 5xx.`);
      neg.push(`- **Setup.** A sandbox event built by the journey up to this step (a second copy, so the journey's own event is untouched).`);
      neg.push(`- **Steps.** Send \`${e.endpoint}\` exactly as the journey does. ${how}.`);
      neg.push(`- **Expected.** A clean refusal: HTTP 4xx with an error message; nothing is created or changed.`);
      neg.push(`- **Oracle.** status in 400–499 (never 2xx, never 5xx); a follow-up read shows no change.`);
      neg.push(`- **Trace.** ${pr} · automate-later · \`apiAssertions.ts\` · \`${k}\``, "");
    }
  }
}
writeFileSync(join(CASES, "api-request-negatives.md"), neg.join("\n"));

// ── report ─────────────────────────────────────────────────────────────────
console.log(`Samples: ${samples.length} responses from ${catalog.fromRuns.length} run(s)`);
for (const k of ordered) {
  const e = catalog.steps[k];
  console.log(`  ${k.padEnd(22)} ${e.endpoint.padEnd(52).slice(0, 52)} samples ${String(e.samples).padStart(2)} · ${e.assertions.length} assertions`);
}
console.log(`Field assertions: ${total}  →  test-cases/api-field-assertions.md`);
console.log(`Request negatives: ${negN}  →  test-cases/api-request-negatives.md`);
console.log(`Catalog: ${ASSERTIONS_FILE}`);
console.log("Next: npm run cases:import");
