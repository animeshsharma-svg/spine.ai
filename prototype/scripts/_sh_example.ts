import { config as loadEnv } from "dotenv";
loadEnv();
import { Stagehand, localBrowser } from "@browserbasehq/stagehand";
import { z } from "zod";
import { STAGEHAND } from "../config/settings.js";
const log = (m: string) => console.log(`[${new Date().toISOString().slice(11,19)}] ${m}`);
const T = <T,>(p: Promise<T>, ms: number, n: string) => Promise.race([p, new Promise<T>((_,r)=>setTimeout(()=>r(new Error(n+" timed out "+ms)),ms))]);
log("launch…");
const browser = await localBrowser.launch({ headless: true });
log("create…");
const sh = await T(Stagehand.create({ browser, model:{ modelName: STAGEHAND.model as any, apiKey: process.env.GOOGLE_API_KEY }, domSettleTimeoutMs: 8000 }), 60000, "create");
log("goto example.com…");
const ctx: any = sh.browser.context; const page = ctx.pages()[0] ?? await ctx.newPage();
await page.goto("https://example.com", { waitUntil: "domcontentloaded" });
log("observe…");
const o: any = await T(sh.observe("the 'More information' link"), 40000, "observe");
log("observe -> " + (Array.isArray(o)?o.length+" found":JSON.stringify(o).slice(0,80)));
log("extract…");
const e: any = await T(sh.extract("the main heading text", z.object({ heading: z.string() }) as any), 40000, "extract");
log("extract -> " + JSON.stringify(e).slice(0,120));
await sh.close();
log("DONE ok");
