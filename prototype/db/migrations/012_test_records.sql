-- spine.ai's OWN database (SPINE_DB_URL) — never Procol's.
--
-- 012: the LEDGER of what spine.ai created on Procol's environments.
--
-- Every run builds things on UAT: draft events, rounds, bids, proposals, POs,
-- QA vendor companies. Procol is never changed by hand and nothing real is
-- deleted, so the platform must be able to answer, for any record on UAT:
-- did we make it, which run made it, is it still there, may it be cleaned up?
--
--   test_records  one row per Procol record spine.ai created (or adopted, e.g.
--                 a shared test event reused by many cases), keyed by its
--                 Procol uuid/id per environment, with the run that made it
--                 and its cleanup state.
--
-- Cleanup states:
--   active          exists on UAT and is still in use (or not yet checked)
--   cleanup-pending marked for cleanup; nothing has been done yet
--   cleaned         spine.ai withdrew / closed / archived it through the API
--   left-in-place   deliberately kept (evidence for a defect, a shared fixture)
--   cleanup-failed  a cleanup was tried and Procol refused it
--   gone            no longer found on UAT (deleted by someone else)
--
-- Idempotent: every statement can run again without error.

CREATE TABLE IF NOT EXISTS test_records (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id              bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  environment_id      bigint NOT NULL,
  company_id          bigint NOT NULL,             -- the buyer workspace it belongs to (target_companies.id)
  record_type         text NOT NULL CHECK (record_type IN (
                        'event', 'stage', 'line-item', 'trade-product', 'bid', 'surrogate-bid', 'proposal',
                        'approval-flow', 'evaluation-form', 'technical-form', 'technical-page', 'template-response',
                        'event-version', 'purchase-order', 'vendor-company', 'vendor-user', 'buyer-user', 'other')),
  procol_uuid         text,                        -- Procol's encoded uuid ('RFFEY0RO')
  procol_id           bigint,                      -- Procol's numeric id, when known
  procol_ref          text,                        -- what a person sees: 'RFX-14510'
  -- uuid when there is one, else the numeric id: the natural key
  procol_key          text GENERATED ALWAYS AS (coalesce(procol_uuid, procol_id::text)) STORED,
  title               text,
  -- test records are named QA_Platform_… / API_Test_… / API_Journey_… (hard rule 1);
  -- anything else in this ledger is a red flag the dashboard can show
  named_as_test       boolean GENERATED ALWAYS AS (title IS NULL OR title ~ '^(QA_Platform|API_Test|API_Journey|QA_)') STORED,
  created_by_run_id   text,
  created_by_label    text,                        -- 'run-all batch', 'matrix', 'invite+vendor_signup' …
  created_at          timestamptz NOT NULL,
  last_used_at        timestamptz,                 -- the newest run that touched it
  use_count           integer NOT NULL DEFAULT 1 CHECK (use_count >= 1),
  cleanup_state       text NOT NULL DEFAULT 'active' CHECK (cleanup_state IN ('active', 'cleanup-pending', 'cleaned', 'left-in-place', 'cleanup-failed', 'gone')),
  cleanup_note        text,
  cleaned_at          timestamptz,
  details             jsonb NOT NULL DEFAULT '{}',
  updated_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, environment_id, record_type, procol_key),
  UNIQUE (org_id, id),
  CHECK (procol_uuid IS NOT NULL OR procol_id IS NOT NULL),
  CHECK ((cleanup_state = 'cleaned') = (cleaned_at IS NOT NULL)),
  FOREIGN KEY (org_id, environment_id) REFERENCES environments (org_id, id),
  FOREIGN KEY (org_id, company_id) REFERENCES target_companies (org_id, id),
  FOREIGN KEY (org_id, created_by_run_id) REFERENCES test_runs (org_id, id) ON DELETE SET NULL (created_by_run_id)
);
CREATE INDEX IF NOT EXISTS test_records_company ON test_records (org_id, company_id, created_at DESC);
CREATE INDEX IF NOT EXISTS test_records_state ON test_records (org_id, cleanup_state, record_type);
CREATE INDEX IF NOT EXISTS test_records_run ON test_records (created_by_run_id);

-- Which runs used which record (a shared test event is used by hundreds of cases).
CREATE TABLE IF NOT EXISTS test_record_uses (
  org_id     bigint NOT NULL,
  record_id  bigint NOT NULL,
  run_id     text NOT NULL,
  role       text NOT NULL CHECK (role IN ('created', 'used')),
  at         timestamptz NOT NULL,
  PRIMARY KEY (record_id, run_id),
  FOREIGN KEY (org_id, record_id) REFERENCES test_records (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, run_id) REFERENCES test_runs (org_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS test_record_uses_run ON test_record_uses (run_id);

CREATE OR REPLACE TRIGGER test_records_touch BEFORE UPDATE ON test_records FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
