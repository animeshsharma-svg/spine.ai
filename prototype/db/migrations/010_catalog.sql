-- spine.ai's OWN database (SPINE_DB_URL) — never Procol's.
--
-- 010: WHAT is tested — the catalog, which until now lived only in files
-- (config/featureTree.ts, data/journeys.json, data/test-cases.json,
-- data/api-cases*.json, data/compiled-plans/). The files stay the authoring
-- source; `npm run db:sync-catalog` copies them in, and a run that saves a
-- result records the exact case version it ran.
--
--   features        the feature tree: groups and their leaf features
--   journeys        the buyer/vendor journeys the catalog is grouped into
--   test_cases      one row per case id, whatever wrote it (written catalog,
--                   runnable library, assistant draft, template check, matrix,
--                   cross-check, or a case only ever seen in a run)
--   case_versions   every distinct content a case has had, by sha256 hash. A
--                   result points at the version it ran — so "it passed last
--                   week" can be told apart from "a different case passed".
--   compiled_plans  the automation compiled from a case (API or UI plan),
--                   versioned by hash, with the compiler's coverage verdict
--
-- Idempotent: every statement can run again without error.

CREATE TABLE IF NOT EXISTS features (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id           bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  key              text NOT NULL CHECK (key ~ '^[a-z0-9_]+(\.[a-z0-9_]+)?$'),  -- 'events' | 'events.publish'
  kind             text NOT NULL CHECK (kind IN ('group', 'feature')),
  parent_id        bigint,                         -- the group, for a feature
  label            text NOT NULL,
  description      text NOT NULL DEFAULT '',
  position         integer NOT NULL,               -- order in the tree (order is meaning)
  journey_step     integer CHECK (journey_step IS NULL OR journey_step > 0),
  portal           text CHECK (portal IS NULL OR portal IN ('buyer', 'vendor', 'both')),
  requires_config  text,                           -- the per-company flag it needs
  flow_id          text,
  ui_flow          text,
  retired_at       timestamptz,                    -- gone from the tree; kept for history
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, key),
  UNIQUE (org_id, id),
  CHECK ((kind = 'group') = (parent_id IS NULL)),
  FOREIGN KEY (org_id, parent_id) REFERENCES features (org_id, id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS journeys (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id      bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  key         text NOT NULL CHECK (key ~ '^[a-z0-9_-]+$'),
  title       text NOT NULL,
  persona     text,
  goal        text,
  position    integer NOT NULL,
  ui_groups   text[] NOT NULL DEFAULT '{}',
  api_groups  text[] NOT NULL DEFAULT '{}',
  retired_at  timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, key),
  UNIQUE (org_id, id)
);

CREATE TABLE IF NOT EXISTS test_cases (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id              bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  case_key            text NOT NULL CHECK (length(case_key) BETWEEN 2 AND 160),  -- EDGE-PUB-019
  -- who wrote it. 'catalog' wins when a written case also has a library copy.
  origin              text NOT NULL CHECK (origin IN ('catalog', 'library', 'generated', 'template-check', 'matrix', 'crosscheck', 'pasted', 'observed')),
  layer               text NOT NULL DEFAULT 'unknown' CHECK (layer IN ('api', 'ui', 'api+ui', 'unknown')),
  feature_id          bigint,
  journey_id          bigint,
  group_key           text,                    -- UI-ENV, API-EVDRJB, EDGE-PUB …
  priority            text CHECK (priority IS NULL OR priority ~ '^P[0-4]$'),
  current_version_id  bigint,                  -- FK added below (case_versions is created after)
  retired_at          timestamptz,             -- no longer in any source file
  first_seen_at       timestamptz NOT NULL DEFAULT now(),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, case_key),
  UNIQUE (org_id, id),
  FOREIGN KEY (org_id, feature_id) REFERENCES features (org_id, id) ON DELETE SET NULL (feature_id),
  FOREIGN KEY (org_id, journey_id) REFERENCES journeys (org_id, id) ON DELETE SET NULL (journey_id)
);
CREATE INDEX IF NOT EXISTS test_cases_feature ON test_cases (org_id, feature_id);
CREATE INDEX IF NOT EXISTS test_cases_journey ON test_cases (org_id, journey_id);

CREATE TABLE IF NOT EXISTS case_versions (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id        bigint NOT NULL,
  case_id       bigint NOT NULL,
  version       integer NOT NULL CHECK (version >= 1),     -- 1, 2, 3 … per case
  content_hash  text NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
  title         text NOT NULL,
  -- { written: <the catalog entry>, automation: <the library entry> } — what
  -- the hash is computed over (canonical JSON, keys sorted)
  content       jsonb NOT NULL,
  source        text,                                       -- the file it came from
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (case_id, content_hash),
  UNIQUE (case_id, version),
  UNIQUE (org_id, id),
  FOREIGN KEY (org_id, case_id) REFERENCES test_cases (org_id, id) ON DELETE CASCADE
);

DO $$ BEGIN
  ALTER TABLE test_cases ADD CONSTRAINT test_cases_current_version_fk
    FOREIGN KEY (org_id, current_version_id) REFERENCES case_versions (org_id, id) ON DELETE SET NULL (current_version_id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS compiled_plans (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id           bigint NOT NULL,
  case_id          bigint NOT NULL,
  case_version_id  bigint,                       -- the case content it was compiled from, when known
  kind             text NOT NULL CHECK (kind IN ('api', 'ui')),
  plan_version     integer NOT NULL CHECK (plan_version >= 1),
  plan_hash        text NOT NULL CHECK (plan_hash ~ '^[0-9a-f]{64}$'),
  -- how much of the written case the plan really tests (the compiler's verdict)
  coverage         text NOT NULL CHECK (coverage IN ('full', 'partial', 'none')),
  gaps             text[] NOT NULL DEFAULT '{}',
  warnings         text[] NOT NULL DEFAULT '{}',
  compiled_by      text,                         -- 'rules' | 'llm-fast' | 'llm' …
  compiled_at      timestamptz NOT NULL,
  plan             jsonb NOT NULL,
  source           text,                         -- data/compiled-plans/api/API-AUTH-001.json
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (case_id, kind, plan_hash),
  UNIQUE (case_id, kind, plan_version),
  UNIQUE (org_id, id),
  FOREIGN KEY (org_id, case_id) REFERENCES test_cases (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, case_version_id) REFERENCES case_versions (org_id, id) ON DELETE SET NULL (case_version_id)
);

CREATE OR REPLACE TRIGGER features_touch BEFORE UPDATE ON features FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
CREATE OR REPLACE TRIGGER journeys_touch BEFORE UPDATE ON journeys FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
CREATE OR REPLACE TRIGGER test_cases_touch BEFORE UPDATE ON test_cases FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
