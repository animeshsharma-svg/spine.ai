-- spine.ai's OWN database (SPINE_DB_URL) — never Procol's.
--
-- 013: DEFECTS — what spine.ai found wrong in Procol, as data. The bug
-- workbook (docs/bugs/Procol_bugs_found_*.xlsx) becomes a VIEW of these rows
-- (scripts/export-bug-sheet.ts) instead of a hand-kept file.
--
--   defects              one row per finding: a verified bug (BUG-xx), a
--                        behaviour that needs product confirmation (Q-xx), or a
--                        client data problem (D-xx). The wording columns are
--                        the workbook's columns, word for word.
--   defect_companies     the clients it was found on, in the order written
--   defect_cases         the EXACT test cases that show it (never "similar")
--   defect_occurrences   the run results that reproduced it
--   defect_status_history every status change, with who and when
--   support_ticket_defects  HubSpot tickets (007) that report the same defect
--
-- Status lifecycle:
--   needs-confirmation → open | wont-fix   (product decides whether it is a bug)
--   open → confirmed                       (reproduced on fresh test records)
--   confirmed → fixed | wont-fix           (Procol answered)
--   fixed → confirmed                      (it came back: a regression)
-- `ref` is assigned once and never renumbered.
--
-- Idempotent: every statement can run again without error.

CREATE TABLE IF NOT EXISTS defects (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id               bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  ref                  text NOT NULL CHECK (ref ~ '^(BUG|Q|D)-[0-9]{2,}$'),
  category             text NOT NULL CHECK (category IN ('bug', 'question', 'data-problem')),
  status               text NOT NULL CHECK (status IN ('open', 'confirmed', 'fixed', 'wont-fix', 'needs-confirmation')),
  title                text NOT NULL CHECK (length(btrim(title)) > 0),  -- "Bug" / "Behaviour" / "Problem"
  area                 text,                                            -- "Area" (not on data problems)
  description          text NOT NULL,                                   -- "What goes wrong" / "What we saw" / "Details"
  how_to_see           text,                                            -- "How to see it" (numbered steps)
  expected_behaviour   text,                                            -- "What should happen"
  actual_behaviour     text,                                            -- "What actually happens"
  severity             text CHECK (severity IS NULL OR severity IN ('Critical', 'High', 'Medium', 'Low')),
  kind                 text,                                            -- "Kind": Server crash, Business rule …
  verification         text,                                            -- "How it was verified"
  to_confirm           text,                                            -- "What to confirm" (questions)
  suggested_fix        text,                                            -- "Suggested fix" (data problems)
  last_confirmed_on    date,                                            -- "Last confirmed"
  first_seen_at        timestamptz,
  last_seen_at         timestamptz,
  sheet_position       integer NOT NULL CHECK (sheet_position >= 1),    -- row order within its sheet
  source               text,                                            -- the workbook it was imported from
  status_changed_at    timestamptz NOT NULL DEFAULT now(),
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, ref),
  UNIQUE (org_id, id),
  -- the ref prefix and the category say the same thing
  CHECK ((category = 'bug') = (ref LIKE 'BUG-%')),
  CHECK ((category = 'question') = (ref LIKE 'Q-%')),
  CHECK ((category = 'data-problem') = (ref LIKE 'D-%')),
  -- a verified bug always carries a severity and a kind
  CHECK (category <> 'bug' OR (severity IS NOT NULL AND kind IS NOT NULL)),
  CHECK (first_seen_at IS NULL OR last_seen_at IS NULL OR last_seen_at >= first_seen_at)
);
CREATE INDEX IF NOT EXISTS defects_status ON defects (org_id, category, status, sheet_position);

CREATE TABLE IF NOT EXISTS defect_companies (
  org_id      bigint NOT NULL,
  defect_id   bigint NOT NULL,
  company_id  bigint NOT NULL,
  position    integer NOT NULL CHECK (position >= 1),
  PRIMARY KEY (defect_id, company_id),
  UNIQUE (defect_id, position),
  FOREIGN KEY (org_id, defect_id) REFERENCES defects (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, company_id) REFERENCES target_companies (org_id, id)
);

CREATE TABLE IF NOT EXISTS defect_cases (
  org_id      bigint NOT NULL,
  defect_id   bigint NOT NULL,
  case_key    text NOT NULL,             -- exactly as written in the workbook's "Test cases"
  case_id     bigint,                    -- resolved, when the case is in the catalog
  position    integer NOT NULL CHECK (position >= 1),
  PRIMARY KEY (defect_id, case_key),
  UNIQUE (defect_id, position),
  FOREIGN KEY (org_id, defect_id) REFERENCES defects (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, case_id) REFERENCES test_cases (org_id, id) ON DELETE SET NULL (case_id)
);
CREATE INDEX IF NOT EXISTS defect_cases_case ON defect_cases (org_id, case_key);

CREATE TABLE IF NOT EXISTS defect_occurrences (
  org_id      bigint NOT NULL,
  defect_id   bigint NOT NULL,
  result_id   bigint NOT NULL,
  run_id      text NOT NULL,
  company_id  bigint NOT NULL,
  seen_at     timestamptz NOT NULL,
  -- 'exact-case': a failed result of one of the defect's own cases
  -- 'manual': a person linked it
  basis       text NOT NULL CHECK (basis IN ('exact-case', 'manual')),
  PRIMARY KEY (defect_id, result_id),
  FOREIGN KEY (org_id, defect_id) REFERENCES defects (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, result_id) REFERENCES run_results (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, run_id) REFERENCES test_runs (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, company_id) REFERENCES target_companies (org_id, id)
);
CREATE INDEX IF NOT EXISTS defect_occurrences_result ON defect_occurrences (result_id);
CREATE INDEX IF NOT EXISTS defect_occurrences_seen ON defect_occurrences (org_id, defect_id, seen_at DESC);

CREATE TABLE IF NOT EXISTS defect_status_history (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id              bigint NOT NULL,
  defect_id           bigint NOT NULL,
  from_status         text,
  to_status           text NOT NULL,
  changed_at          timestamptz NOT NULL DEFAULT now(),
  changed_by_user_id  bigint REFERENCES users (id) ON DELETE SET NULL,
  changed_by_label    text,
  note                text,
  FOREIGN KEY (org_id, defect_id) REFERENCES defects (org_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS defect_status_history_defect ON defect_status_history (defect_id, changed_at DESC);

-- The status history is written by the database, so no writer can forget it.
-- The writer may name itself for the row with set_config('app.actor', '<label>', true).
-- AFTER for INSERT (the row must exist for the history's foreign key), BEFORE
-- for UPDATE (so status_changed_at is set on the row itself).
CREATE OR REPLACE FUNCTION spine_defect_status_log_after() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO defect_status_history (org_id, defect_id, from_status, to_status, changed_by_label)
  VALUES (NEW.org_id, NEW.id, NULL, NEW.status, nullif(current_setting('app.actor', true), ''));
  RETURN NULL;
END $$;
CREATE OR REPLACE FUNCTION spine_defect_status_log_before() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    NEW.status_changed_at := now();
    INSERT INTO defect_status_history (org_id, defect_id, from_status, to_status, changed_by_label)
    VALUES (NEW.org_id, NEW.id, OLD.status, NEW.status, nullif(current_setting('app.actor', true), ''));
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER defects_status_insert AFTER INSERT ON defects FOR EACH ROW EXECUTE FUNCTION spine_defect_status_log_after();
CREATE OR REPLACE TRIGGER defects_status_update BEFORE UPDATE ON defects FOR EACH ROW EXECUTE FUNCTION spine_defect_status_log_before();
CREATE OR REPLACE TRIGGER defects_touch BEFORE UPDATE ON defects FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();

-- HubSpot tickets (007, which predates organisations) gain an owner and a link
-- to the defect they report. The column is nullable so the existing writer
-- (src/hubspot/store.ts) keeps working unchanged; the backfill fills it.
ALTER TABLE support_tickets ADD COLUMN IF NOT EXISTS org_id bigint REFERENCES organisations (id) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS support_ticket_defects (
  org_id      bigint NOT NULL,
  ticket_id   text NOT NULL REFERENCES support_tickets (ticket_id) ON DELETE CASCADE,
  defect_id   bigint NOT NULL,
  linked_at   timestamptz NOT NULL DEFAULT now(),
  linked_by   text,
  PRIMARY KEY (ticket_id, defect_id),
  FOREIGN KEY (org_id, defect_id) REFERENCES defects (org_id, id) ON DELETE CASCADE
);
