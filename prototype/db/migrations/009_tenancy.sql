-- spine.ai's OWN database (SPINE_DB_URL) — never Procol's.
--
-- 009: WHO the data belongs to. Until now every row was implicitly "ours";
-- a product needs to say whose. See docs/DATA_MODEL.md for the full design.
--
--   organisations     a spine.ai customer (Procol is the first). Every tenant
--                     row in 010+ carries org_id, and row-level security
--                     (015_row_level_security.sql) keys on it.
--   environments      where an organisation's product runs (UAT …): base URLs
--                     only. NEVER secrets — `secrets_ref` names where the
--                     credentials live, it never holds them.
--   target_companies  the companies (Procol clients) tests run as, per
--                     environment: 198678 PROCOL DEMO, 32461 Demo Account 2 …
--   users             people and service identities (nightly, ci …). Global:
--                     one person can belong to several organisations.
--   roles             the four roles and what each may do (reference data).
--   memberships       user × organisation × role.
--   audit_log         append-only: who did what to which row, and when.
--
-- Conventions for every table from here on: bigint identity ids, timestamptz
-- everywhere, enums as CHECK constraints on text (cheap to widen later — see
-- 008), NOT NULL unless "unknown" is a real answer, and UNIQUE (org_id, id) on
-- every tenant table so children can use composite foreign keys that make it
-- impossible for a row of one organisation to point at a row of another.
--
-- Idempotent: every statement can run again without error.

-- ── organisations ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS organisations (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug                     text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,62}$'),
  name                     text NOT NULL CHECK (length(btrim(name)) > 0),
  status                   text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'closed')),
  -- days are counted in this zone (the dashboard's "today"); IST for Procol
  timezone                 text NOT NULL DEFAULT 'Asia/Kolkata',
  -- evidence older than this is deleted by spine_apply_retention() unless a
  -- defect needs it (see 016_retention.sql)
  evidence_retention_days  integer NOT NULL DEFAULT 90 CHECK (evidence_retention_days BETWEEN 1 AND 3650),
  created_at               timestamptz NOT NULL DEFAULT now(),
  updated_at               timestamptz NOT NULL DEFAULT now()
);

-- ── environments ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS environments (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id         bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  key            text NOT NULL CHECK (key ~ '^[a-z0-9][a-z0-9_-]{0,31}$'),   -- 'uat'
  name           text NOT NULL,                                                 -- 'UAT'
  kind           text NOT NULL CHECK (kind IN ('uat', 'staging', 'production', 'local', 'other')),
  api_base_url   text NOT NULL CHECK (api_base_url ~ '^https?://'),
  console_url    text CHECK (console_url IS NULL OR console_url ~ '^https?://'),
  vendor_url     text CHECK (vendor_url IS NULL OR vendor_url ~ '^https?://'),
  -- may spine.ai create test records here? (never on production by default)
  allows_writes  boolean NOT NULL DEFAULT true,
  -- WHERE credentials live, by name ("procol test/.env"). Never a secret.
  secrets_ref    text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, key),
  UNIQUE (org_id, id)
);

-- ── target companies ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS target_companies (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id              bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  environment_id      bigint NOT NULL,
  procol_company_id   integer NOT NULL CHECK (procol_company_id > 0),     -- Procol's companies.id
  name                text NOT NULL CHECK (length(btrim(name)) > 0),
  role                text NOT NULL DEFAULT 'buyer' CHECK (role IN ('buyer', 'vendor', 'sandbox')),
  is_primary          boolean NOT NULL DEFAULT false,                    -- the default client for runs
  active              boolean NOT NULL DEFAULT true,
  notes               text,
  -- the newest settings/templates snapshot (002 model_snapshots) for this company
  latest_snapshot_id  bigint REFERENCES model_snapshots (id) ON DELETE SET NULL,
  first_seen_at       timestamptz,                                       -- first run against it
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (org_id, environment_id, procol_company_id),
  UNIQUE (org_id, id),
  FOREIGN KEY (org_id, environment_id) REFERENCES environments (org_id, id) ON DELETE CASCADE
);
-- at most one primary company per organisation and environment
CREATE UNIQUE INDEX IF NOT EXISTS target_companies_one_primary
  ON target_companies (org_id, environment_id) WHERE is_primary;

-- ── users, roles, memberships ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text NOT NULL CHECK (email ~ '^[^@\s]+@[^@\s]+$'),
  display_name  text NOT NULL,
  -- 'service' = a non-human caller (nightly, ci, backend-watch, assistant)
  kind          text NOT NULL DEFAULT 'person' CHECK (kind IN ('person', 'service')),
  status        text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  last_seen_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_key ON users (lower(email));

CREATE TABLE IF NOT EXISTS roles (
  role                text PRIMARY KEY CHECK (role IN ('owner', 'admin', 'qa', 'viewer')),
  rank                integer NOT NULL UNIQUE,      -- higher can do everything lower can
  description         text NOT NULL,
  can_read            boolean NOT NULL,
  can_run             boolean NOT NULL,             -- start runs, create test records on UAT
  can_edit_catalog    boolean NOT NULL,             -- cases, plans, features
  can_manage_defects  boolean NOT NULL,             -- change a defect's status, link cases
  can_manage_members  boolean NOT NULL,             -- invite, change roles
  can_manage_org      boolean NOT NULL              -- environments, companies, retention, delete
);
INSERT INTO roles (role, rank, description, can_read, can_run, can_edit_catalog, can_manage_defects, can_manage_members, can_manage_org) VALUES
