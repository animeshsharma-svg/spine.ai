  rank = EXCLUDED.rank, description = EXCLUDED.description, can_read = EXCLUDED.can_read, can_run = EXCLUDED.can_run,
  can_edit_catalog = EXCLUDED.can_edit_catalog, can_manage_defects = EXCLUDED.can_manage_defects,
  can_manage_members = EXCLUDED.can_manage_members, can_manage_org = EXCLUDED.can_manage_org;

CREATE TABLE IF NOT EXISTS memberships (
  org_id      bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  user_id     bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role        text NOT NULL REFERENCES roles (role),
  invited_by  bigint REFERENCES users (id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, user_id)
);
CREATE INDEX IF NOT EXISTS memberships_user ON memberships (user_id);

-- ── audit log ───────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS audit_log (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id        bigint NOT NULL REFERENCES organisations (id) ON DELETE CASCADE,
  at            timestamptz NOT NULL DEFAULT now(),
  actor_user_id bigint REFERENCES users (id) ON DELETE SET NULL,
  actor_label   text NOT NULL,                 -- 'owner@spine.local', 'backfill', 'nightly' …
  action        text NOT NULL CHECK (action ~ '^[a-z_]+\.[a-z_.]+$'),  -- 'defect.status_changed'
  entity_type   text NOT NULL,                 -- 'defect', 'test_record', 'evidence' …
  entity_id     text NOT NULL,                 -- the row's id or natural key (BUG-04)
  summary       text,                          -- one plain-English sentence
  before        jsonb,
  after         jsonb
);
CREATE INDEX IF NOT EXISTS audit_log_org_at ON audit_log (org_id, at DESC);
CREATE INDEX IF NOT EXISTS audit_log_entity ON audit_log (org_id, entity_type, entity_id, at DESC);

-- Append-only: history that can be rewritten is not history. Deleting the
-- whole organisation (CASCADE) is the one way rows leave.
CREATE OR REPLACE FUNCTION spine_audit_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM organisations o WHERE o.id = OLD.org_id) THEN
    RETURN OLD;  -- the organisation itself is being deleted
  END IF;
  RAISE EXCEPTION 'audit_log is append-only (% refused)', TG_OP;
END $$;
CREATE OR REPLACE TRIGGER audit_log_append_only
  BEFORE UPDATE OR DELETE ON audit_log
  FOR EACH ROW EXECUTE FUNCTION spine_audit_append_only();

-- updated_at, kept honest by the database rather than by every writer
CREATE OR REPLACE FUNCTION spine_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER organisations_touch BEFORE UPDATE ON organisations FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
CREATE OR REPLACE TRIGGER environments_touch BEFORE UPDATE ON environments FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
CREATE OR REPLACE TRIGGER target_companies_touch BEFORE UPDATE ON target_companies FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
CREATE OR REPLACE TRIGGER users_touch BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();
CREATE OR REPLACE TRIGGER memberships_touch BEFORE UPDATE ON memberships FOR EACH ROW EXECUTE FUNCTION spine_touch_updated_at();

-- ── the tenant context (used by every row-level-security policy, 015) ──────
-- The application sets these per transaction:
--   SELECT set_config('app.org_id', '<id>', true);   -- a tenant request
--   SELECT set_config('app.role', 'service', true);   -- platform internals
-- Unset = no organisation = no rows (fail closed).
CREATE OR REPLACE FUNCTION spine_current_org() RETURNS bigint
  LANGUAGE sql STABLE PARALLEL SAFE AS $$ SELECT nullif(current_setting('app.org_id', true), '')::bigint $$;

-- Platform internals (the run writer, backfill, retention, reconcile) work
-- across organisations. The login role that serves tenant traffic is named
-- spine_app (see docs/DATA_MODEL.md, "Row-level security"); it can never take
-- this path even if it sets app.role.
CREATE OR REPLACE FUNCTION spine_is_service() RETURNS boolean
  LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT coalesce(current_setting('app.role', true), '') = 'service' AND current_user <> 'spine_app'
$$;

CREATE OR REPLACE FUNCTION spine_row_visible(row_org bigint) RETURNS boolean
  LANGUAGE sql STABLE PARALLEL SAFE AS $$ SELECT spine_is_service() OR row_org = spine_current_org() $$;
